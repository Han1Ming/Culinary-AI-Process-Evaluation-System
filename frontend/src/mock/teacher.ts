/** 按问题与附件挑一条回答；附件优先于关键词 */
export function mockTeacherReply(question: string, attachments: ChatAttachment[] = []): string {
  const image = attachments.find((a) => a.kind === 'image')
  const pdf = attachments.find((a) => a.kind === 'pdf')

  if (pdf) {
    return `${PDF_REPLY}\n\n> 已读取：${pdf.name}（${kb(pdf.size)}）`
  }
  if (image) {
    return `${IMAGE_REPLY}\n\n> 已读取图片：${image.name}（${kb(image.size)}）`
  }

  const text = question.toLowerCase()
  const hit = RULES.find((rule) => rule.keys.some((key) => text.includes(key)))
  if (hit) return hit.reply

  return DEFAULT_REPLY
}
